#!/bin/sh
# install-fhn-presence.sh — install the raw-BLE Loshall Tag presence scanner
# on the Home Assistant OS host.
#
# Run this from the host shell (SSH & Web Terminal add-on), as root, after
# copying the upload directory:
#   cp /mnt/user/share/tmp_fhn_presence/install-fhn-presence.sh /tmp/ && sh /tmp/install-fhn-presence.sh
#
# The script assumes the uploaded files (fhn_presence.zip, requirements.txt,
# fhn_presence.service) live in /mnt/user/share/tmp_fhn_presence/
# (i.e. /config/tmp_fhn_presence/ as seen from the HA container).
set -eu

SRC=/mnt/user/share/tmp_fhn_presence
DEST=/opt/fhn_presence
CONFIG_ENTRY_JSON=/mnt/user/share/.storage/core.config_entries

if [ ! -f "$SRC/fhn_presence.zip" ]; then
    echo "ERROR: $SRC/fhn_presence.zip not found — upload the files first." >&2
    exit 1
fi

echo "==> BLE adapter check"
if [ ! -d /sys/class/bluetooth ]; then
    echo "ERROR: no bluetooth adapter found (expected /sys/class/bluetooth/hci0)." >&2
    exit 1
fi
hciconfig 2>/dev/null | grep -q "UP" || hciconfig hci0 up 2>/dev/null || true

echo "==> install files to $DEST"
mkdir -p "$DEST"
cp "$SRC/fhn_presence.zip" "$SRC/requirements.txt" "$DEST/"
cd "$DEST"
rm -rf scanner
unzip -o fhn_presence.zip >/dev/null

echo "==> python venv (first run only)"
if [ ! -x "$DEST/venv/bin/python" ]; then
    python3 -m venv "$DEST/venv"
    "$DEST/venv/bin/pip" install --no-cache-dir -r "$DEST/requirements.txt"
fi

echo "==> generate $DEST/fhn_presence.env"
# Key material comes from the existing HA integration config entry
# (domain = ha_findmy_offline_tag_tracker): fields name / clock_offset /
# curve / ephemeral_identity_key.
EXTRACT_TMP=$(mktemp)
if python3 - "$CONFIG_ENTRY_JSON" "$EXTRACT_TMP" <<'PY'
import json, sys
try:
    data = json.load(open(sys.argv[1]))
    for e in data["data"]["entries"]:
        if e.get("domain") == "ha_findmy_offline_tag_tracker":
            d = e["data"]
            with open(sys.argv[2], "w") as f:
                f.write(
                    f"{d['ephemeral_identity_key']} {d['clock_offset']} "
                    f"{d['curve']} {d.get('name', 'Loshall Tag')}\n"
                )
            break
    else:
        raise ValueError("no ha_findmy_offline_tag_tracker entry")
except Exception as exc:  # noqa: BLE001
    sys.stderr.write(f"extract failed: {exc}\n")
    sys.exit(1)
PY
then
    read -r EIK OFFSET CURVE NAME < "$EXTRACT_TMP"
fi
rm -f "$EXTRACT_TMP"

if [ -z "$EIK" ]; then
    echo "WARN: could not extract ephemeral_identity_key from $CONFIG_ENTRY_JSON" >&2
    echo "      (HA may not have committed the storage file yet, or awk parsing" >&2
    echo "      missed it). Fill FHN_TAG_EIK / FHN_TAG_CLOCK_OFFSET in" >&2
    echo "      $DEST/fhn_presence.env by hand before restarting the service." >&2
    EIK="<paste the 64-hex Ephemeral Identity Key>"
    OFFSET="<paste the clock offset float>"
    CURVE="secp160r1"
    NAME="Loshall Tag"
fi

cat > "$DEST/fhn_presence.env" <<EOF
# Generated by install-fhn-presence.sh — key material from the HA integration.
FHN_TAG_NAME="$NAME"
FHN_TAG_EIK="$EIK"
FHN_TAG_CLOCK_OFFSET="$OFFSET"
FHN_TAG_CURVE="$CURVE"

# Presence thresholds (seconds). See fhn_presence.env.example for tuning notes.
FHN_NORMAL_THRESHOLD="200"
FHN_ROTATION_THRESHOLD="400"

# MQTT — install the "MQTT broker" add-on first, then fill in the credentials.
FHN_MQTT_URL="mqtt://127.0.0.1:1883"
FHN_MQTT_USER="<add-on user>"
FHN_MQTT_PASS="<add-on password>"
FHN_MQTT_BASE_TOPIC="fhn/losall_tag"

FHN_LOG_LEVEL="INFO"
EOF
chmod 600 "$DEST/fhn_presence.env"
echo "    EIK: ${EIK:0:8}... (len ${#EIK})  offset: $OFFSET  curve: $CURVE"

echo "==> systemd unit"
install -D "$SRC/fhn_presence.service" /etc/systemd/system/fhn_presence.service
systemctl daemon-reload

if grep -q '"<add-on password>"' "$DEST/fhn_presence.env"; then
    echo
    echo "==> NOT starting yet: fill MQTT credentials in $DEST/fhn_presence.env"
    echo "    1. Install the 'MQTT broker' add-on (Add-ons menu, 'Add-on Store')."
    echo "    2. Set a username/password on it (Config > add-on MQTT > settings)."
    echo "    3. Edit $DEST/fhn_presence.env (FHN_MQTT_USER / FHN_MQTT_PASS)."
    echo "    4. systemctl start fhn_presence"
    echo
    echo "    (The in-HA integration keeps working meanwhile as the backstop.)"
else
    systemctl enable --now fhn_presence
    sleep 3
    systemctl --no-pager status fhn_presence | head -12
fi
